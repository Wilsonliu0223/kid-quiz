def more_math_fill():
    """Pad math so each grade has enough unique word problems."""
    for g, start, step, count in [(12, 2, 1, 12), (23, 3, 2, 12), (34, 6, 3, 12), (56, 11, 4, 12)]:
        for i in range(count):
            a = start + i * step
            b = start + 3 + i
            correct = a * b
            wr = []
            for cand in (a + b, abs(a - b) or a + 2, correct + 1, correct - 1, a * (b + 1), (a + 1) * b):
                if cand != correct and cand > 0 and str(cand) not in wr:
                    wr.append(str(cand))
                if len(wr) >= 3:
                    break
            add(
                f"mf{g}-{i}",
                "math",
                g,
                f"{a} 個小朋友每人 {b} 顆糖，一共幾顆？",
                [str(correct), *wr[:3]],
                f"{a}×{b}",
            )


