items: list[dict] = []


def add(iid, cat, grade, q, options, explain, answer=0):
    assert len(options) == 4, iid
    assert len(set(options)) == 4, (iid, options)
    items.append(
        {
            "id": iid,
            "cat": cat,
            "grade": grade,
            "q": q,
            "options": options,
            "answer": answer,
            "explain": explain,
        }
    )


def parse_old():
    import subprocess

    text = subprocess.check_output(
        ["git", "show", "HEAD:js/gifted-bank.js"],
        cwd=ROOT,
        encoding="utf-8",
    )
    for m in re.finditer(
        r'\{ id: "([^"]+)", cat: "([^"]+)", lv: (\d), q: ("(?:\\.|[^"\\])*"), options: (\[[^\]]+\]), answer: (\d), explain: ("(?:\\.|[^"\\])*") \}',
        text,
    ):
        iid, cat, lv, qj, optj, ans, expj = m.groups()
        q = json.loads(qj)
        options = json.loads(optj)
        explain = json.loads(expj)
        grade = 12 if int(lv) == 1 else 23
        add(iid, cat, grade, q, options, explain, int(ans))


def distract(correct, pool, n=3):
    out = []
    for x in pool:
        if x != correct and x not in out:
            out.append(x)
        if len(out) >= n:
            break
    i = 1
    while len(out) < n:
        cand = f"{correct}·{i}"
        if cand != correct:
            out.append(cand)
        i += 1
    return out


