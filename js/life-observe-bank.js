export function lensesOf(node) {
  return (LENS_OF[node.id] || []).map((id) => LENS[id]).filter(Boolean);
}

export function nodeById(id) {
  return NODES.find((n) => n.id === id) || ZONE_NODES.find((n) => n.id === id) || null;
}

export function countyById(id) {
  return COUNTIES.find((c) => c.id === id) || COUNTIES.find((c) => c.id === "txg") || COUNTIES[0];
}

export function zonesForCounty(id) {
  const c = countyById(id);
  return (c.zones || []).map((zid) => nodeById(zid)).filter(Boolean);
}

export function placeNote(nodeId, id) {
  const c = countyById(id);
  return (c.notes && c.notes[nodeId]) || "";
}

export function relJoin(val) {
  if (!val) return { why: "", see: "", think: "" };
  if (typeof val === "string") return { why: val, see: "", think: "" };
  return { why: val.why || "", see: val.see || "", think: val.think || "" };
}

export function relsOf(node, countyId) {
  const rel = { ...(node.rel || {}) };
  if (node.countyCard) {
    for (const z of zonesForCounty(countyId)) {
      rel[z.id] = z.joinFromCounty || z.branch || z.because;
    }
  }
  return rel;
}

export function nodesForRing(ring) {
  return NODES.filter((n) => n.ring === ring);
}

