export const WRITING_GRADES = [2, 3, 4, 5, 6];

const gradeSeq = {};
export const WRITING_BANK = RAW.map((row) => {
  const [grade, title, kind, body, steps, tips] = row;
  gradeSeq[grade] = (gradeSeq[grade] || 0) + 1;
  const extra = EXTRA[title] || "";
  const more = grade >= 5 ? MORE_HIGH[title] || "" : "";
  const full = [body, extra, more].filter(Boolean).join("\n\n");
  return {
    id: `w${grade}-${String(gradeSeq[grade]).padStart(2, "0")}`,
    grade,
    title,
    kind,
    body: full,
    steps,
    tips,
    words: zhLen(full),
  };
});

export function writingByGrade(grade) {
  return WRITING_BANK.filter((item) => item.grade === grade);
}
